/** Anything without its own line gets one of these, picked by the line so it never changes between visits. */
const FALLBACK = ['Hmph.', 'Get to the point.', 'How tedious. Fine.', 'Entertain me, then.', 'Know your place.', 'I\'ll allow it. For now.'];

export function sukunaLine(text: string): string {
  const own = SUKUNA_LINES[text];
  if (own) return own;
  let h = 0;
  for (let i = 0; i < text.length; i++) h = (h * 31 + text.charCodeAt(i)) | 0;
  return FALLBACK[Math.abs(h) % FALLBACK.length];
}
